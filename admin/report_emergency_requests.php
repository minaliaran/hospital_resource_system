    <div class="panel-body">
        <form method="GET" class="filter-bar-form">
            <div class="form-group m-0">
                <label>Resource Type</label>
                <select name="resource" class="form-control">
                    <option value="">All Types</option>
                    <option value="Blood"  <?php echo $filter_res === 'Blood'  ? 'selected' : ''; ?>>Blood</option>
                    <option value="Oxygen" <?php echo $filter_res === 'Oxygen' ? 'selected' : ''; ?>>Oxygen</option>
                </select>
            </div>
            <div class="form-group m-0">
                <label>Status</label>
                <select name="status" class="form-control">
                    <option value="">All Statuses</option>
                    <?php foreach (['Pending','Approved','Rejected','Forwarded','Completed'] as $s): ?>
                    <option value="<?php echo $s; ?>" <?php echo $filter_status === $s ? 'selected' : ''; ?>><?php echo $s; ?></option>
                    <?php endforeach; ?>
                </select>
            </div>
            <button type="submit" class="btn btn-primary">Apply Filter</button>
            <a href="report_emergency_requests.php" class="btn btn-secondary">Reset</a>
        </form>
    </div>
</div>
