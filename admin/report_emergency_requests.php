        <div class="report-header-sub">Colombo District Government Hospitals — Sri Lanka</div>
        <div class="report-header-meta">
            <span><strong>Date Generated:</strong> <?php echo date('Y-m-d H:i'); ?></span>
            <span><strong>Generated By:</strong> <?php echo sanitize($_SESSION['full_name']); ?></span>
        </div>
    </div>
</div>
<div class="page-header">
    <div>
        <div class="page-header-title">Emergency Request Report</div>
        <div class="page-header-subtitle">Visual analytics and log of emergency requests for <strong><?php echo sanitize($hospital_name); ?></strong></div>
    </div>
    <button class="btn btn-secondary btn-print"><i class="fa fa-print"></i> Print</button>
    <button class="btn btn-primary" id="emergencyRequestsPdfBtn" data-pdf-config='<?php echo json_encode($pdf_config, JSON_HEX_APOS | JSON_HEX_QUOT); ?>'><i class="fa fa-file-pdf"></i> Download PDF</button>
</div>
<div class="grid-3-col">
    <div class="panel m-0">
        <div class="panel-header"><span class="panel-title"><i class="fa fa-chart-pie text-primary-icon"></i> Requests by Status</span></div>
        <div class="panel-body chart-panel-body-sm"><canvas id="statusPieChart" width="220" height="220" data-chart-data='<?php echo json_encode(array_values($status_counts)); ?>'></canvas></div>
    </div>
    <div class="panel m-0">
        <div class="panel-header"><span class="panel-title"><i class="fa fa-chart-bar text-danger-icon"></i> Requests by Priority</span></div>
        <div class="panel-body chart-panel-body-sm"><canvas id="priorityBarChart" width="260" height="220" data-chart-data='<?php echo json_encode(array_values($priority_counts)); ?>'></canvas></div>
    </div>
    <div class="panel m-0">
        <div class="panel-header"><span class="panel-title"><i class="fa fa-chart-line text-success"></i> Monthly Request Trend</span></div>
        <div class="panel-body chart-panel-body-sm"><canvas id="monthlyLineChart" width="260" height="220" data-labels='<?php echo json_encode($trend_labels); ?>' data-values='<?php echo json_encode($trend_data); ?>'></canvas></div>
    </div>
</div>
