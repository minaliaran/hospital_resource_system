<?php
$page_title = "Emergency Request Report";
require_once __DIR__ . '/../includes/header.php';
require_role(['admin', 'blood_staff', 'oxygen_staff']);
$h    = $_SESSION['hospital_id'];
$role = $_SESSION['role'];
$filter_res    = $_GET['resource'] ?? '';
$filter_status = $_GET['status']   ?? '';
$all_rows = $conn->query("SELECT status, priority, resource_type, created_at FROM requests WHERE hospital_id = $h")->fetch_all(MYSQLI_ASSOC);
$status_counts   = ['Pending'=>0,'Approved'=>0,'Rejected'=>0,'Forwarded'=>0,'Completed'=>0];
$priority_counts = ['Low'=>0,'Medium'=>0,'High'=>0,'Emergency'=>0];
$monthly_trend   = [];
for ($i = 5; $i >= 0; $i--) {
    $monthly_trend[date('Y-m', strtotime("-$i months"))] = 0;
}
foreach ($all_rows as $r) {
    if (isset($status_counts[$r['status']]))     $status_counts[$r['status']]++;
    if (isset($priority_counts[$r['priority']])) $priority_counts[$r['priority']]++;
    $mk = date('Y-m', strtotime($r['created_at']));
    if (isset($monthly_trend[$mk])) $monthly_trend[$mk]++;
}
$trend_labels = array_map(fn($m) => date('M Y', strtotime($m.'-01')), array_keys($monthly_trend));
$trend_data   = array_values($monthly_trend);
$sql = "SELECT r.*, u.full_name, ap.full_name as approved_by_name
        FROM requests r
        JOIN users u ON r.created_by = u.user_id
        LEFT JOIN users ap ON r.approved_by = ap.user_id
        WHERE r.hospital_id = $h";
if ($filter_res)    $sql .= " AND r.resource_type = '" . $conn->real_escape_string($filter_res) . "'";
if ($filter_status) $sql .= " AND r.status = '"        . $conn->real_escape_string($filter_status) . "'";
$sql .= " ORDER BY r.created_at DESC";
$rows = $conn->query($sql)->fetch_all(MYSQLI_ASSOC);
$pdf_rows = [];
foreach ($rows as $i => $r) {
    $pdf_rows[] = [
        $i + 1,
        $r['full_name'],
        $r['resource_type'] . ($r['blood_group'] ? ' (' . $r['blood_group'] . ')' : '') . ($r['cylinder_type'] ? ' (' . $r['cylinder_type'] . ')' : ''),
        (string)$r['quantity'],
        $r['priority'],
        $r['status'],
        $r['reason'] ?: '—',
        $r['approved_by_name'] ?: '—',
        date('Y-m-d', strtotime($r['created_at']))
    ];
}

$pdf_config = [
    'filename'       => 'Emergency_Request_Report_' . date('Y-m-d') . '.pdf',
    'title'          => 'Emergency Request Report',
    'hospital'       => sanitize($hospital_name),
    'generatedBy'    => sanitize($full_name),
    'date'           => date('d F Y, H:i'),
    'filters'        => [
        ['label' => 'Resource Type', 'value' => $filter_res ?: 'All Types'],
        ['label' => 'Status Filter', 'value' => $filter_status ?: 'All Statuses']
    ],
    'summary'        => [
        ['label' => 'Total Requests', 'value' => (string)count($rows)],
        ['label' => 'Pending',        'value' => (string)$status_counts['Pending']],
        ['label' => 'Approved',       'value' => (string)$status_counts['Approved']],
        ['label' => 'Completed',      'value' => (string)$status_counts['Completed']]
    ],
    'chartIds'       => ['statusPieChart', 'priorityBarChart', 'monthlyLineChart'],
    'chartLabels'    => ['Requests by Status', 'Requests by Priority', 'Monthly Request Trend'],
    'tableHeaders'   => ['No', 'Requested By', 'Resource', 'Qty', 'Priority', 'Status', 'Clinical Reason', 'Processed By', 'Submitted'],
    'colWidths'      => [10, 22, 28, 12, 18, 18, 28, 22, 22],
    'tableRows'      => $pdf_rows,
    'statusColIndex' => 5,
    'notes'          => 'This report compiles the emergency resource requests submitted by staff members. Charts represent status breakdowns, priority distributions, and trends. Clinical reasons should be audited periodically to verify resource allocation alignment.'
];
?>
