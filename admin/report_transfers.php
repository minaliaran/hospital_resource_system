<?php
$page_title = "Inter-Hospital Transfer Report";
require_once __DIR__ . '/../includes/header.php';
require_role('admin');
$h = $_SESSION['hospital_id'];
$filter_status = $_GET['status'] ?? '';
$sql = "SELECT t.*, hf.hospital_name as sender_name, ht.hospital_name as receiver_name
        FROM transfers t
        JOIN hospitals hf ON t.from_hospital_id = hf.hospital_id
        JOIN hospitals ht ON t.to_hospital_id   = ht.hospital_id
        WHERE (t.from_hospital_id = $h OR t.to_hospital_id = $h)";
if ($filter_status) {
    $sql .= " AND t.status = '" . $conn->real_escape_string($filter_status) . "'";
}
$sql .= " ORDER BY t.transfer_date DESC";
$rows = $conn->query($sql)->fetch_all(MYSQLI_ASSOC);
$completed_count = count(array_filter($rows, fn($r) => $r['status'] === 'Completed'));
$in_transit      = count(array_filter($rows, fn($r) => $r['status'] === 'In Transit'));
$pdf_rows = [];
foreach ($rows as $i => $r) {
    $res = $r['resource_type'];
    if ($r['blood_group'])   $res .= ' ' . $r['blood_group'];
    if ($r['cylinder_type']) $res .= ' ' . $r['cylinder_type'];
    $pdf_rows[] = [
        'T-' . str_pad($r['transfer_id'], 3, '0', STR_PAD_LEFT),
        $r['sender_name'],
        $r['receiver_name'],
        $res,
        $r['quantity'],
        $r['driver_name'],
        $r['status'],
        date('M j, Y', strtotime($r['transfer_date'])),
    ];
}

$pdf_config = [
    'filename'       => 'Transfer_Report_' . date('Y-m-d') . '.pdf',
    'title'          => 'Inter-Hospital Transfer Report',
    'hospital'       => sanitize($hospital_name),
    'generatedBy'    => sanitize($full_name),
    'date'           => date('d F Y, H:i'),
    'filters'        => [
        ['label' => 'Transfer Status', 'value' => $filter_status ?: 'All Statuses']
    ],
    'summary'        => [
        ['label' => 'Total Transfers', 'value' => (string)count($rows)],
        ['label' => 'Completed',       'value' => (string)$completed_count],
        ['label' => 'In Transit',      'value' => (string)$in_transit]
    ],
    'chartIds'       => [],
    'tableHeaders'   => ['ID', 'Sender', 'Receiver', 'Resource', 'Qty', 'Driver', 'Status', 'Date'],
    'colWidths'      => [14, 38, 38, 28, 10, 26, 18, 28],
    'tableRows'      => $pdf_rows,
    'statusColIndex' => 6,
    'notes'          => 'This report provides an audit log of inter-hospital resource transfers involving ' . sanitize($hospital_name) . '. All outgoing and incoming transfers are listed with sender, receiver, resource type, driver, and vehicle details. Completed transfers confirm successful resource delivery between hospitals.'
];
