
function generateReportPDF(config) {
    if (typeof window.jspdf === 'undefined' || typeof window.jspdf.jsPDF === 'undefined') {
        alert('PDF library (jsPDF) is not loaded on this page.\nPlease contact the system administrator.');
        return;
    }
    const { jsPDF } = window.jspdf;
    const doc       = new jsPDF('p', 'mm', 'a4');
    const pageW     = 210;
    const pageH     = 297;
    const margin    = 14;
    const contentW  = pageW - margin * 2;
    const C = {
        primary:  [37,  99,  235],
        dark:     [15,  23,  42],
        text:     [30,  41,  59],
        muted:    [100, 116, 139],
        border:   [226, 232, 240],
        rowEven:  [248, 250, 252],
        success:  [16,  185, 129],
        warning:  [245, 158, 11],
        danger:   [239, 68,  68],
        info:     [14,  165, 233],
        white:    [255, 255, 255],
        headerBg: [15,  23,  42],
    };
    let y       = 0;
    let pageNum = 1;
    const rgb = (c) => ({ r: c[0], g: c[1], b: c[2] });
    function setColor(c)     { doc.setTextColor(c[0], c[1], c[2]); }
    function setFill(c)      { doc.setFillColor(c[0], c[1], c[2]); }
    function setDraw(c)      { doc.setDrawColor(c[0], c[1], c[2]); }
    function setLineW(w)     { doc.setLineWidth(w); }
    function hRule(yy, color) {
        color = color || C.border;
        setDraw(color);
        setLineW(0.2);
        doc.line(margin, yy, pageW - margin, yy);
    }
    function checkPage(needed) {
        if (y + needed > pageH - 18) {
            drawFooter();
            doc.addPage();
            pageNum++;
            y = margin;
            return true;
        }
        return false;
    }
    function drawFooter() {
        const fy = pageH - 8;
        setFill(C.primary);
        doc.rect(0, pageH - 14, pageW, 14, 'F');
        doc.setFontSize(6.5);
        doc.setFont('helvetica', 'normal');
        setColor(C.white);
        doc.text('Generated by Hospital Resource Coordination System — Colombo District Government Hospitals', margin, fy - 2);
        doc.text('This is a computer-generated report.', margin, fy + 2.5);
        doc.text(`Page ${pageNum}`, pageW - margin, fy, { align: 'right' });
    }
    function sectionTitle(label) {
        checkPage(14);
        y += 2;
        setFill(C.primary);
        doc.rect(margin, y, 3.5, 6, 'F');
        doc.setFontSize(8.5);
        doc.setFont('helvetica', 'bold');
        setColor(C.primary);
        doc.text(label, margin + 5.5, y + 4.5);
        y += 9;
    }
    setFill(C.headerBg);
    doc.rect(0, 0, pageW, 28, 'F');
    setFill(C.primary);
    doc.rect(0, 28, pageW, 2, 'F');
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    setColor(C.white);
    doc.text('Hospital Resource Coordination System', margin, 11);
    doc.setFontSize(7.5);
    doc.setFont('helvetica', 'normal');
    setColor([148, 163, 184]);  
    doc.text('Colombo District Government Hospitals  ·  Sri Lanka', margin, 17.5);
    doc.setFontSize(8);
    doc.setFont('helvetica', 'bold');
    setColor([96, 165, 250]);   
    doc.text('OFFICIAL REPORT', margin, 24.5);
    y = 36;
    doc.setFontSize(16);
    doc.setFont('helvetica', 'bold');
    setColor(C.dark);
    doc.text(config.title, pageW / 2, y, { align: 'center' });
    y += 8;
    hRule(y, C.primary);
    setLineW(0.4);
    doc.line(margin, y + 0.4, pageW - margin, y + 0.4);
    y += 7;
    const col2 = margin + contentW / 2 + 5;
    doc.setFontSize(7);
    doc.setFont('helvetica', 'bold');
    setColor(C.muted);
    doc.text('HOSPITAL',       margin, y);
    doc.text('GENERATED BY',   col2, y);
    y += 3.5;
    doc.setFontSize(8.5);
    doc.setFont('helvetica', 'bold');
    setColor(C.text);
    doc.text(config.hospital,    margin, y);
    doc.text(config.generatedBy, col2, y);
    y += 5;
    doc.setFontSize(7);
    doc.setFont('helvetica', 'bold');
    setColor(C.muted);
    doc.text('GENERATED DATE', margin, y);
    y += 3.5;
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    setColor(C.text);
    doc.text(config.date, margin, y);
    y += 7;
    hRule(y);
    y += 7;
    if (config.filters && config.filters.length > 0) {
        sectionTitle('FILTER DETAILS');
        setFill(C.rowEven);
        doc.rect(margin, y, contentW, config.filters.length * 6 + 3, 'F');
        config.filters.forEach((f, i) => {
            doc.setFontSize(7.5);
            doc.setFont('helvetica', 'bold');
            setColor(C.muted);
            doc.text(f.label + ':', margin + 3, y + 4.5);
            doc.setFont('helvetica', 'normal');
            setColor(C.text);
            doc.text(String(f.value), margin + 42, y + 4.5);
            y += 6;
        });
        y += 4;
        hRule(y);
        y += 7;
    }
    if (config.summary && config.summary.length > 0) {
        sectionTitle('REPORT SUMMARY');
        const perRow = Math.min(config.summary.length, 4);
        const gap    = 3;
        const boxW   = (contentW - gap * (perRow - 1)) / perRow;
        const boxH   = 16;
        let   bx     = margin;
        let   rowTopY = y;
        let   col    = 0;
        config.summary.forEach((s, i) => {
            setDraw(C.border);
            setFill(C.white);
            setLineW(0.25);
            doc.rect(bx, rowTopY, boxW, boxH, 'FD');
            setFill(C.primary);
            doc.rect(bx, rowTopY, 2, boxH, 'F');
            doc.setFontSize(13);
            doc.setFont('helvetica', 'bold');
            setColor(C.primary);
            doc.text(String(s.value), bx + boxW / 2, rowTopY + 8, { align: 'center' });
            doc.setFontSize(6);
            doc.setFont('helvetica', 'normal');
            setColor(C.muted);
            doc.text(s.label.toUpperCase(), bx + boxW / 2, rowTopY + 13.5, { align: 'center' });
            col++;
            bx += boxW + gap;
            if (col === perRow) {
                rowTopY += boxH + gap;
                bx = margin;
                col = 0;
            }
        });
        y = rowTopY + (col > 0 ? boxH + gap : 0) + 2;
        hRule(y);
        y += 7;
    }
    if (config.chartIds && config.chartIds.length > 0) {
        const validCharts = config.chartIds
            .map(id => document.getElementById(id))
            .filter(c => c !== null);
        if (validCharts.length > 0) {
            sectionTitle('CHARTS & ANALYTICS');
            checkPage(70);
            const perRow = Math.min(validCharts.length, 2);
            const gap    = 4;
            const cW     = (contentW - gap * (perRow - 1)) / perRow;
            const cH     = 58;
            let   cx     = margin;
            let   rowY   = y;
            let   col    = 0;
            validCharts.forEach((canvas, i) => {
                checkPage(cH + 10);
                setFill(C.rowEven);
                setDraw(C.border);
                setLineW(0.2);
                doc.rect(cx, rowY, cW, cH, 'FD');
                try {
                    const imgData = canvas.toDataURL('image/png');
                    doc.addImage(imgData, 'PNG', cx + 2, rowY + 2, cW - 4, cH - 4, undefined, 'FAST');
                } catch(e) {
                    doc.setFontSize(7);
                    setColor(C.muted);
                    doc.text('[Chart unavailable]', cx + cW / 2, rowY + cH / 2, { align: 'center' });
                }
                if (config.chartLabels && config.chartLabels[i]) {
                    doc.setFontSize(6.5);
                    doc.setFont('helvetica', 'italic');
                    setColor(C.muted);
                    doc.text(config.chartLabels[i], cx + cW / 2, rowY + cH + 4, { align: 'center' });
                }
                col++;
                cx += cW + gap;
                if (col >= perRow) {
                    rowY += cH + (config.chartLabels ? 10 : 6);
                    cx = margin;
                    col = 0;
                }
            });
            y = rowY + (col > 0 ? cH + 6 : 0) + 2;
            hRule(y);
            y += 7;
        }
    }
    if (config.tableHeaders && config.tableRows && config.tableRows.length > 0) {
        sectionTitle('REPORT DATA');
        const headers   = config.tableHeaders;
        const rows      = config.tableRows;
        const colCount  = headers.length;
        const colWidths = config.colWidths || Array(colCount).fill(contentW / colCount);
        const cellH     = 6.5;
        const headH     = 8;
        checkPage(headH + cellH + 4);
        setFill(C.primary);
        doc.rect(margin, y, contentW, headH, 'F');
        doc.setFontSize(7);
        doc.setFont('helvetica', 'bold');
        setColor(C.white);
        let hx = margin;
        headers.forEach((h, i) => {
            doc.text(h, hx + 2, y + 5.5);
            hx += colWidths[i];
        });
        y += headH;
        rows.forEach((row, rowIdx) => {
            checkPage(cellH + 2);
            if (rowIdx % 2 === 0) {
                setFill(C.rowEven);
                doc.rect(margin, y, contentW, cellH, 'F');
            }
            setDraw(C.border);
            setLineW(0.15);
            doc.line(margin, y + cellH, margin + contentW, y + cellH);
            doc.setFontSize(7);
            doc.setFont('helvetica', 'normal');
            let cx = margin;
            row.forEach((cell, ci) => {
                const txt = String(cell);
                if (config.statusColIndex !== undefined && ci === config.statusColIndex) {
                    const tl = txt.toLowerCase();
                    if (['available','completed','approved','accepted','sent'].includes(tl))   setColor(C.success);
                    else if (['critical','out of stock','rejected','failed'].includes(tl))      setColor(C.danger);
                    else if (['low','pending','in transit','forwarded'].includes(tl))           setColor(C.warning);
                    else setColor(C.text);
                } else {
                    setColor(ci === 0 ? C.muted : C.text);
                }
                const maxW = colWidths[ci] - 3;
                let display = txt;
                if (doc.getTextWidth(display) > maxW) {
                    while (doc.getTextWidth(display + '…') > maxW && display.length > 1) {
                        display = display.slice(0, -1);
                    }
                    display += '…';
                }
                doc.text(display, cx + 2, y + 4.7);
                cx += colWidths[ci];
            });
            setDraw(C.border);
            doc.line(margin, y, margin, y + cellH);
            doc.line(margin + contentW, y, margin + contentW, y + cellH);
            y += cellH;
        });
        setDraw(C.border);
        setLineW(0.3);
        doc.line(margin, y, margin + contentW, y);
        y += 9;
    } else if (config.tableHeaders) {
        checkPage(20);
        sectionTitle('REPORT DATA');
        setFill(C.rowEven);
        doc.rect(margin, y, contentW, 14, 'F');
        doc.setFontSize(8);
        setColor(C.muted);
        doc.text('No records found for the selected filters.', pageW / 2, y + 8, { align: 'center' });
        y += 19;
    }
    if (config.notes) {
        checkPage(25);
        sectionTitle('REPORT NOTES');
        setFill([239, 246, 255]);  
        setDraw([147, 197, 253]);  
        setLineW(0.2);
        const noteLines = doc.splitTextToSize(config.notes, contentW - 8);
        const noteH     = noteLines.length * 5 + 8;
        doc.rect(margin, y, contentW, noteH, 'FD');
        doc.setFontSize(7.5);
        doc.setFont('helvetica', 'normal');
        setColor(C.text);
        noteLines.forEach((line, li) => {
            doc.text(line, margin + 4, y + 6 + li * 5);
        });
        y += noteH + 5;
    }
    drawFooter();
    doc.save(config.filename);
}
